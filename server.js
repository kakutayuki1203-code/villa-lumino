/* ===================================
   POST /api/chat — Claude APIへのSSEプロキシ
   =================================== */
app.post('/api/chat', async (req, res) => {
  const { messages } = req.body;

  /* バリデーション */
  if (!Array.isArray(messages) || messages.length === 0) {
    return res.status(400).json({ error: 'messages が不正です' });
  }

  /* SSEヘッダーを設定 */
  res.setHeader('Content-Type', 'text/event-stream; charset=utf-8');
  res.setHeader('Cache-Control', 'no-cache');
  res.setHeader('Connection', 'keep-alive');
  res.flushHeaders();

  try {
    /* Claude APIにストリーミングリクエスト */
    const stream = client.messages.stream({
      model: 'claude-opus-4-6',
      system: SYSTEM_PROMPT,
      messages: messages,
      max_tokens: 1024,
      thinking: { type: 'adaptive' },
    });

    /* テキストデルタをSSEで逐次送信 */
    for await (const event of stream) {
      if (
        event.type === 'content_block_delta' &&
        event.delta.type === 'text_delta'
      ) {
        const data = JSON.stringify({ text: event.delta.text });
        res.write(`data: ${data}\n\n`);
      }
    }

    /* ストリーム終了シグナル */
    res.write('data: [DONE]\n\n');
    res.end();

  } catch (err) {
    console.error('Claude API エラー:', err.message);
    /* エラーをSSEで通知してから終了 */
    const errData = JSON.stringify({ error: 'AIとの通信に失敗しました。しばらくしてから再試行してください。' });
    res.write(`data: ${errData}\n\n`);
    res.write('data: [DONE]\n\n');
    res.end();
  }
});

